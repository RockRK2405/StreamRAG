def engine_of(p):
    return p.last.engine if isinstance(p, FullRestartPipeline) else p.engine


def make_stack(index_root: Path, corpus: Path):
    cfg = load_config(REPO / "configs" / "default.yaml",
                      {"paths.corpus": str(corpus), "paths.index_root": str(index_root),
                       "telemetry.log_level": "ERROR", "multi_intent.enabled": True, "session.enabled": True},
                      base_dir=REPO)
    return build_stack(cfg, build_index(cfg).path)


def run_session(stack, case, restart=False, on_turn=None):
    """Run a dev session; ``on_turn(turn, result, engine)`` is called right after each turn (state as of that turn)."""
    p = FullRestartPipeline(stack) if restart else AdaptivePipeline(stack)
    for n, t in enumerate(case["turns"], start=1):
        res = p.process(t["utterance_id"], t["utterance_text"], n * GAP_MS)
        if on_turn is not None:
            on_turn(t, res, engine_of(p))
    return p


def terms_of(stack):
    an = stack.bundle.analyzer
    return lambda w: list(dict.fromkeys(an.tokens(w)))


# ------------------------------------------------------------------------------------------------ dev suite
def dev_suite(stacks, cases, restart=False):
    rows, per_case = [], []
    for case in cases:
        st = stacks[case["corpus"]]
        tf = terms_of(st)
        crow = []

        def score(t, res, eng):
            r = score_turn(eng, res, t["gold"], tf)
            r.update(case_id=case["case_id"], category=case["category"], utterance_id=t["utterance_id"],
                     text=t["utterance_text"], gate=res.gate, total_ms=res.timings_ms.get("total"))
            crow.append(r)
        p = run_session(st, case, restart, score)
        rows += crow
        per_case.append({"case_id": case["case_id"], "category": case["category"], "turns": crow})
        p.close()
    by_cat = {}
    for c in sorted({r["category"] for r in rows}):
        by_cat[c] = aggregate([r for r in rows if r["category"] == c])
    return {"aggregate": aggregate(rows), "by_category": by_cat, "cases": per_case}


# ------------------------------------------------------------------------------------------------ delta / restart
def turn_metrics(res, eng, prev_counters, prev_records: set[str]) -> dict:
    ev_now = set(eng.store.records)
    plan = res.plan
    reused_ev = len(plan.evidence_to_retain) if plan else 0
    return {"retrievals": res.retrievals, "cache_hits": res.cache_hits, "reused_active": res.reused_active,
            "retrieval_ms": res.timings_ms.get("retrieval", 0.0), "total_ms": res.timings_ms.get("total", 0.0),
            "evidence_retained": reused_ev,
            "new_evidence": len(ev_now - prev_records),
            "claims_revalidated": eng.counters.get("claims_revalidated", 0) - prev_counters.get("claims_revalidated", 0),
            "claims_affected": len(plan.claims_to_revalidate) if plan else 0,
            "changes": [c.change_type for c in res.changes]}


def delta_vs_restart(stacks, cases):
    rows = []
    for case in cases:
        st = stacks[case["corpus"]]
        for mode in ("incremental", "full_restart"):
            p = FullRestartPipeline(st) if mode == "full_restart" else AdaptivePipeline(st)
            prev_c, prev_ev = {}, set()
            for n, t in enumerate(case["turns"], start=1):
                res = p.process(t["utterance_id"], t["utterance_text"], n * GAP_MS)
                eng = engine_of(p)
                if mode == "full_restart":                          # a fresh session each turn: nothing carried
                    prev_c, prev_ev = {}, set()
                m = turn_metrics(res, eng, prev_c, prev_ev)
                m.update(case_id=case["case_id"], turn=n, mode=mode)
                rows.append(m)
                prev_c, prev_ev = dict(eng.counters), set(eng.store.records)
            p.close()
    changed = [r for r in rows if r["turn"] > 1 and r["changes"] != ["NO_CHANGE"]]

    def summ(mode, rs):
        rs = [r for r in rs if r["mode"] == mode]
        return {"turns": len(rs), "retrieval_calls": sum(r["retrievals"] for r in rs),
                "cache_hits": sum(r["cache_hits"] for r in rs), "reused_active": sum(r["reused_active"] for r in rs),
                "evidence_retained": sum(r["evidence_retained"] for r in rs),
                "new_evidence": sum(r["new_evidence"] for r in rs),
                "retrieval_ms": pct([r["retrieval_ms"] for r in rs]), "total_ms": pct([r["total_ms"] for r in rs]),
                "claims_revalidated": sum(r["claims_revalidated"] for r in rs)}
    example = [r for r in rows if r["case_id"] == "S01" and r["turn"] == 2]
    return {"follow_up_turns_with_a_change": {m: summ(m, changed) for m in ("incremental", "full_restart")},
            "all_turns": {m: summ(m, rows) for m in ("incremental", "full_restart")},
            "example_S01_constraint_added": example, "rows": rows,
            "note": "new_evidence for full_restart counts every evidence record of the fresh session (nothing is "
                    "carried over); evidence_retained counts (evidence, need) assignments kept usable without retrieval"}


# ------------------------------------------------------------------------------------------------ answer refinement
def answer_refinement(stacks, cases):
    by_id = {c["case_id"]: c for c in cases}
    out = {}
    for name, cid, turn in REFINEMENT_CASES:
        case = by_id[cid]
        st = stacks[case["corpus"]]
        row = {"case_id": cid, "turn": turn, "utterances": [t["utterance_text"] for t in case["turns"][:turn]]}
        for mode in ("incremental", "full_restart"):
            p = FullRestartPipeline(st) if mode == "full_restart" else AdaptivePipeline(st)
            for n, t in enumerate(case["turns"][:turn - 1], start=1):
                p.process(t["utterance_id"], t["utterance_text"], n * GAP_MS)
            before = dict(engine_of(p).counters) if mode == "incremental" else {}
            n_ans = len(engine_of(p).answers.versions) if mode == "incremental" else 0
            t = case["turns"][turn - 1]
            res = p.process(t["utterance_id"], t["utterance_text"], turn * GAP_MS)
            eng = engine_of(p)
            ans = res.answer
            d = ans.diff if ans is not None else None
            row[mode] = {
                "changes": [c.change_type for c in res.changes], "new_retrievals": res.retrievals,
                "reused": res.cache_hits + res.reused_active,
                "affected_claims": len(res.plan.claims_to_revalidate) if res.plan else 0,
                "revalidated_claims": eng.counters.get("claims_revalidated", 0) - before.get("claims_revalidated", 0),
                "unchanged_claims": len(d.kept) if d else len(eng.answers.versions[-1].claim_ids) if
                eng.answers.versions else 0,
                "answer_changed": ans is not None and (mode == "full_restart" or len(eng.answers.versions) > n_ans),
                "answer_kind": ans.kind if ans else None,
                "diff": {"kept": len(d.kept), "modified": len(d.modified), "added": len(d.added),
                         "retracted": len(d.retracted), "sections_regenerate": [s.section_id for s in ans.sections
                                                                                if s.needs_regeneration],
                         "sections_unchanged": d.sections_unchanged, "uncertainty_introduced":
                         d.uncertainty_introduced} if d else None,
                "turn_ms": res.timings_ms.get("total")}
            p.close()
        out[name] = row
    return out


# ------------------------------------------------------------------------------------------------ ablation
def ablation(stacks, cases, count, tok_name):
    rows = {"A_no_memory": [], "B_full_transcript": [], "C_structured": []}
    for case in cases:
        st = stacks[case["corpus"]]
        tf = terms_of(st)
        inc = AdaptivePipeline(st)
        texts = []
        for n, t in enumerate(case["turns"], start=1):
            texts.append(t["utterance_text"])
            gold = t["gold"]
            for arm in rows:
                t0 = time.perf_counter()
                if arm == "C_structured":
                    p, uid, text = inc, t["utterance_id"], t["utterance_text"]
                else:
                    p = AdaptivePipeline(st)
                    uid, text = "u1", (t["utterance_text"] if arm == "A_no_memory" else " ".join(texts))
                res = p.process(uid, text, n * GAP_MS)
                wall = (time.perf_counter() - t0) * 1000.0
                eng = p.engine
                r = score_turn(eng, res, gold, tf)
                if arm == "C_structured":
                    pkg = RelevantContextSelector(eng.memory, count, tok_name).select("structured")
                    ctx = pkg.size_by_kind["conversation"]
                    ctx_retr = pkg.size_by_kind["retrieval"]
                else:
                    ctx = RelevantContextSelector(eng.memory, count, tok_name).select("none").size
                    ctx_retr = None
                rows[arm].append({"case_id": case["case_id"], "turn": n, "needs_ok": r["needs_ok"],
                                  "needs_gold": r["needs_gold"], "leaks": len(r["isolation_leaks"]),
                                  "retrievals": res.retrievals, "wall_ms": round(wall, 4),
                                  "context_chars": ctx.chars, "context_tokens": ctx.tokens,
                                  "retrieval_context_tokens": ctx_retr.tokens if ctx_retr else None,
                                  "gold_evidence_found": r["gold_evidence_found"], "gold_evidence": r["gold_evidence"]})
                if arm != "C_structured":
                    p.close()
        inc.close()
    summary = {}
    for arm, rs in rows.items():
        g = sum(r["needs_gold"] for r in rs)
        e = sum(r["gold_evidence"] for r in rs)
        summary[arm] = {
            "turns": len(rs), "context_correctness_need_queries": round(sum(r["needs_ok"] for r in rs) / g, 4),
            "query_context_leaks": sum(r["leaks"] for r in rs), "retrieval_calls": sum(r["retrievals"] for r in rs),
            "wall_ms_per_turn": pct([r["wall_ms"] for r in rs]),
            "conversation_context_tokens_per_turn": pct([r["context_tokens"] for r in rs]),
            "conversation_context_chars_per_turn": pct([r["context_chars"] for r in rs]),
            "gold_evidence_recall_fixture": round(sum(r["gold_evidence_found"] for r in rs) / e, 4) if e else None}
    summary["C_structured"]["retrieval_context_tokens_per_turn"] = pct(
        [r["retrieval_context_tokens"] for r in rows["C_structured"]])
    return {"summary": summary, "rows": rows, "tokenizer": tok_name,
            "definitions": {
                "A_no_memory": "each turn interpreted alone (fresh session, current utterance only)",
                "B_full_transcript": "each turn: a fresh session over the concatenated transcript so far",
                "C_structured": "the adaptive session (frames, needs, constraints, evidence, claims)",
                "context_tokens": "tokens of the conversation context the arm carries (A: the utterance; B: the "
                                  "transcript; C: structured needs / constraints / entities of the active frame), "
                                  "measured with the bge-small WordPiece tokenizer as a proxy (the Phase 7 "
                                  "generator's tokenizer is not known)"}}


# ------------------------------------------------------------------------------------------------ latency / compute
STAGES = ("interpretation", "change_detection", "delta_planning", "retrieval", "evidence_update", "claim_revalidation",
          "answer_update", "total")


def latency(stacks, cases, reps):
    per = {}                                                  # (case, turn, mode) -> [timings dicts]
    for _ in range(reps):
        for case in cases:
            st = stacks[case["corpus"]]
            for mode in ("incremental", "full_restart"):
                p = FullRestartPipeline(st) if mode == "full_restart" else AdaptivePipeline(st)
                for n, t in enumerate(case["turns"], start=1):
                    res = p.process(t["utterance_id"], t["utterance_text"], n * GAP_MS)
                    per.setdefault((case["case_id"], n, mode), []).append(
                        (res.timings_ms, [c.change_type for c in res.changes]))
                p.close()
    med = {}
    for k, xs in per.items():
        med[k] = ({s: statistics.median(x[0].get(s, 0.0) for x in xs) for s in STAGES}, xs[0][1])
    out = {}
    for label, sel in (("follow_up_turns_with_a_change", lambda n, ch: n > 1 and ch != ["NO_CHANGE"]),
                       ("all_turns", lambda n, ch: True)):
        res = {}
        for mode in ("incremental", "full_restart"):
            rows = [v for (c, n, m), v in med.items() if m == mode and sel(n, v[1])]
            res[mode] = {s: pct([r[0][s] for r in rows]) for s in STAGES}
            res[mode]["sum_of_median_totals_ms"] = round(sum(r[0]["total"] for r in rows), 3)
        inc, rst = res["incremental"]["sum_of_median_totals_ms"], res["full_restart"]["sum_of_median_totals_ms"]
        res["latency_saving"] = round((rst - inc) / rst, 4) if rst else None
        pairs = [(med[(c, n, "incremental")][0]["total"], med[(c, n, "full_restart")][0]["total"])
                 for (c, n, m), v in med.items() if m == "incremental" and sel(n, v[1])]
        res["per_turn_saving"] = pct([(b - a) / b for a, b in pairs if b > 0])
        out[label] = res
    return {"reps": reps, "statistic": "median over reps per turn, then p50/p95/mean over turns", **out}


def compute(stacks, cases, count):
    tot = {m: {"retrieval_calls": 0, "queries_reused": 0, "evidence_retained": 0, "claims_revalidated": 0,
               "claims_kept_in_answers": 0, "rerender_input_tokens": 0, "rerender_sections": 0, "sections_total": 0}
           for m in ("incremental", "full_restart")}
    for case in cases:
        st = stacks[case["corpus"]]
        for mode in tot:
            p = FullRestartPipeline(st) if mode == "full_restart" else AdaptivePipeline(st)
            for n, t in enumerate(case["turns"], start=1):
                res = p.process(t["utterance_id"], t["utterance_text"], n * GAP_MS)
                eng = engine_of(p)
                tot[mode]["retrieval_calls"] += res.retrievals
                tot[mode]["queries_reused"] += res.cache_hits + res.reused_active
                if res.plan:
                    tot[mode]["evidence_retained"] += len(res.plan.evidence_to_retain)
                if res.answer is not None:
                    a = res.answer
                    regen = [s for s in a.sections if s.needs_regeneration or mode == "full_restart"]
                    tot[mode]["rerender_sections"] += len(regen)
                    tot[mode]["sections_total"] += len(a.sections)
                    tot[mode]["rerender_input_tokens"] += sum(count(eng.graph.claims[c].text) for s in regen
                                                              for c in s.claim_ids)
                    if mode == "incremental":
                        tot[mode]["claims_kept_in_answers"] += len(a.diff.kept)
            tot[mode]["claims_revalidated"] += engine_of(p).counters.get("claims_revalidated", 0) if mode == \
                "incremental" else 0
            p.close()
    # full restart re-validates every claim of every fresh session: count them per turn
    rst_reval = 0
    for case in cases:
        st = stacks[case["corpus"]]
        p = FullRestartPipeline(st)
        for n, t in enumerate(case["turns"], start=1):
            p.process(t["utterance_id"], t["utterance_text"], n * GAP_MS)
            rst_reval += p.last.engine.counters.get("claims_revalidated", 0)
        p.close()
    tot["full_restart"]["claims_revalidated"] = rst_reval
    i, r = tot["incremental"], tot["full_restart"]
    return {"totals": tot, "retrieval_calls_avoided": r["retrieval_calls"] - i["retrieval_calls"],
            "retrieval_calls_avoided_rate": round(1 - i["retrieval_calls"] / r["retrieval_calls"], 4),
            "claim_revalidations_avoided": r["claims_revalidated"] - i["claims_revalidated"],
            "rerender_input_tokens_avoided": r["rerender_input_tokens"] - i["rerender_input_tokens"],
            "note": "re-render input tokens = tokens (bge-small WordPiece, proxy) of the claim texts in the answer "
                    "sections Phase 7 would have to re-render; no generation tokens exist yet (no generator)"}


