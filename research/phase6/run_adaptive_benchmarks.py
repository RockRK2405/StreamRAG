def demo_trace(stacks, cases):
    case = next(c for c in cases if c["case_id"] == "S01")
    st = stacks["fixture"]
    run = run_virtual(st.cfg, st.service, st.policy, stream_inputs(case), index_hash=st.index_hash,
                      intent_stack=st.intent_stack)
    dump_trace(run.events, OUT / "demo_trace.jsonl")
    texts = {t["utterance_id"]: t["utterance_text"] for t in case["turns"]}
    claims = {}
    lines = ["# Phase 6 demonstration trace (generated)", "",
             f"> {BANNER}. Generated by `research/phase6/run_adaptive_benchmarks.py` from a virtual streaming run "
             "of dev session S01 over the fictional fixture corpus; every line below is printed from the run's "
             "telemetry events (`demo_trace.jsonl`), nothing is hand-written.", ""]
    shown_utt = set()
    for e in run.events:
        t, p, u = e.type.value, e.payload, e.utterance_id
        if u and u not in shown_utt:                                      # first event of the utterance
            shown_utt.add(u)
            lines += ["", f"## USER ({u}): \"{texts[u]}\" (streamed in chunks)", ""]
        if t == "CLAIM_CREATED":
            claims[p["claim_id"]] = p["text"]
        line = None
        if t == "CONTEXT_CHANGE_DETECTED":
            line = (f"context change {p['change_id']}: **{p['change_type']}** affected={p['affected_intents']} "
                    f"new={p['new_intents']} +{p['added_constraints']} -{p['removed_constraints']} cue={p['cue']!r} "
                    f"confidence={p['confidence']}")
        elif t == "DELTA_PLAN_CREATED":
            line = (f"delta plan {p['plan_id']}: create={[q['query']['text'] for q in p['queries_to_create']]} "
                    f"reuse={[(q['action'], q['reused_query_id']) for q in p['queries_to_reuse']]} "
                    f"supersede={p['queries_to_supersede']} retain={len(p['evidence_to_retain'])} "
                    f"revalidate={p['evidence_to_revalidate']} claims_to_revalidate={p['claims_to_revalidate']}")
        elif t == "QUERY_GENERATED":
            line = (f"{p['query_id']} generated ({p['trigger']}): {p['query_text']!r} parent={p.get('parent_query_id')}"
                    f" from_change={p.get('derived_from_change_id')}")
        elif t == "QUERY_REUSED":
            line = f"query reused ({p['action']}): {p['reused_query_id']} -> {p['query_id']}"
        elif t == "RETRIEVAL_STARTED":
            line = f"{p['query_id']} retrieval starts"
        elif t == "RETRIEVAL_COMPLETED":
            line = f"{p['query_id']} retrieved {p['evidence_ids']}"
        elif t in ("EVIDENCE_RETAINED", "EVIDENCE_INVALIDATED", "EVIDENCE_REVALIDATED"):
            line = f"evidence {p['evidence_id']}@{p['intent_id']}: {p['from_status']} -> {p['to_status']} ({p['rule']})"
        elif t == "CLAIM_CREATED":
            line = f"claim {p['claim_id']} registered: {p['text']!r} <- {p['evidence_ids']}"
        elif t in ("CLAIM_INVALIDATED", "CLAIM_REVALIDATED"):
            line = f"claim {p['claim_id']}: {p['from_status']} -> {p['to_status']} ({p['reason']})"
        elif t in ("ANSWER_VERSION_CREATED", "ANSWER_VERSION_UPDATED"):
            d = p["diff"]
            line = (f"**answer state {p['answer_id']}** (v{p['version']}, {p['kind']}, frame {p['frame_id']}): "
                    f"{p['change_summary']}\n    - modified: {[(m['claim_id'], m['from_status'], m['to_status'], claims.get(m['claim_id'])) for m in d['modified']]}\n"
                    f"    - added: {[(c, claims.get(c)) for c in d['added']]}\n"
                    f"    - unchanged: {[(c, claims.get(c)) for c in d['kept']]}\n"
                    f"    - retracted: {d['retracted']}; sections to re-render: "
                    f"{[s['section_id'] for s in p['sections'] if s['needs_regeneration']]}")
        elif t == "UTTERANCE_FINALIZED":
            line = f"utterance {u} finalized: {p['transcript']!r}"
        elif t == "SESSION_VERSION_CREATED":
            line = f"session state v{p['version_id']} (parent {p['parent_version']}, {p['trigger']}): {p['summary']}"
        if line:
            lines.append(f"- `{e.t_session_ms:8.1f} ms` {line}")
    (OUT / "demo_trace.md").write_text("\n".join(lines) + "\n")
    return {"events": len(run.events), "lines": len(lines)}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--index-root", type=Path, required=True)
    ap.add_argument("--reps", type=int, default=7)
    a = ap.parse_args()
    t0 = time.time()
    stacks = {"fixture": make_stack(a.index_root / "fixture", REPO / "tests/fixtures/corpus"),
              "conflict": make_stack(a.index_root / "conflict", REPO / "tests/fixtures/corpus_conflict")}
    cases = load_adaptive_cases(CASES)
    count, tok_name = token_counter(stacks["fixture"].service.embedder)
    OUT.mkdir(parents=True, exist_ok=True)
    meta = {"REPORTABLE": False, "banner": BANNER, "cases": len(cases),
            "turns": sum(len(c["turns"]) for c in cases),
            "index_content_hash": {k: s.index_hash for k, s in stacks.items()},
            "embedder": stacks["fixture"].bundle.dense.info.name if stacks["fixture"].bundle.dense else None,
            "tokenizer_for_token_counts": tok_name}
    for _ in range(2):                                                    # warm-up (ONNX session, caches)
        dev_suite(stacks, cases[:3])
    write_json(OUT / "dev_suite.json", {"meta": meta, **dev_suite(stacks, cases)})
    write_json(OUT / "full_restart.json", {"meta": meta, **dev_suite(stacks, cases, restart=True)})
    stress = load_adaptive_cases(REPO / "eval" / "dev_adaptive_stress")
    write_json(OUT / "stress_suite.json", {"meta": {**meta, "suite": "dev_adaptive_stress (written after code freeze, "
                                                    "run once, code not changed in response)", "cases": len(stress),
                                                    "turns": sum(len(c["turns"]) for c in stress)},
                                           **dev_suite(stacks, stress)})
    write_json(OUT / "delta_retrieval.json", {"meta": meta, **delta_vs_restart(stacks, cases)})
    write_json(OUT / "answer_refinement.json", {"meta": meta, "cases": answer_refinement(stacks, cases)})
    write_json(OUT / "ablation.json", {"meta": meta, **ablation(stacks, cases, count, tok_name)})
    write_json(OUT / "latency.json", {"meta": meta, **latency(stacks, cases, a.reps)})
    write_json(OUT / "compute.json", {"meta": meta, **compute(stacks, cases, count)})
    write_json(OUT / "scaling.json", {"meta": meta, **scaling(stacks, a.reps)})
    write_json(OUT / "streaming_virtual.json", {"meta": meta, **streaming(stacks, cases)})
    write_json(OUT / "replay_check.json", {"meta": meta, "realtime": realtime_replay(stacks, cases)})
    write_json(OUT / "demo_trace_meta.json", {"meta": meta, **demo_trace(stacks, cases)})
    print(f"done in {time.time() - t0:.1f}s -> {OUT}")


if __name__ == "__main__":
    main()
