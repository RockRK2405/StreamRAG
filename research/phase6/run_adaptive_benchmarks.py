LONG_SESSION = [                       # workload over the fixture domain (not gold-scored): one growing topic frame
    "What are the rules for ladders in the orchard?", "What about crates?", "Okay.",
    "Back to the ladders, what about overnight?", "Thanks.", "And what about the tool shed?",
    "Only for the night shift.", "Okay.", "Actually, ignore the night shift restriction.",
    "Never mind the overnight restriction.", "Right.", "What about damaged fruit?", "Specifically after sunset.",
    "Okay, thanks.", "Forget the sunset part.", "What about the crate count?"]


def scaling(stacks, reps):
    st = stacks["fixture"]
    per = {}
    for _ in range(reps):
        for mode in ("incremental", "full_restart"):
            p = FullRestartPipeline(st) if mode == "full_restart" else AdaptivePipeline(st)
            for n, text in enumerate(LONG_SESSION, start=1):
                res = p.process(f"u{n}", text, n * GAP_MS)
                eng = engine_of(p)
                per.setdefault((n, mode), []).append(
                    (res.timings_ms.get("total", 0.0), res.retrievals, [c.change_type for c in res.changes],
                     len([i for i in (eng.frames.active.intent_ids if eng.frames.active else [])
                          if eng.tracker.intents[i].status == "ACTIVE"])))
            p.close()
    rows = []
    for n, text in enumerate(LONG_SESSION, start=1):
        inc, rst = per[(n, "incremental")], per[(n, "full_restart")]
        rows.append({"turn": n, "text": text, "changes": inc[0][2], "frame_needs": inc[0][3],
                     "incremental_ms": round(statistics.median(x[0] for x in inc), 4),
                     "full_restart_ms": round(statistics.median(x[0] for x in rst), 4),
                     "incremental_retrievals": inc[0][1], "full_restart_retrievals": rst[0][1]})
    tot_i, tot_r = sum(r["incremental_ms"] for r in rows), sum(r["full_restart_ms"] for r in rows)
    return {"reps": reps, "turns": len(rows), "rows": rows,
            "retrievals": {"incremental": sum(r["incremental_retrievals"] for r in rows),
                           "full_restart": sum(r["full_restart_retrievals"] for r in rows)},
            "sum_of_median_turn_ms": {"incremental": round(tot_i, 3), "full_restart": round(tot_r, 3)},
            "latency_saving": round((tot_r - tot_i) / tot_r, 4) if tot_r else None,
            "last_4_turns_ms": {"incremental": [r["incremental_ms"] for r in rows[-4:]],
                                "full_restart": [r["full_restart_ms"] for r in rows[-4:]]}}


# ------------------------------------------------------------------------------------------------ streaming
def stream_inputs(case, interval_ms=385.0, gap_ms=2500.0):
    evs = [SessionStart(session_id=case["case_id"])]
    off = 0.0
    for t in case["turns"]:
        evs += sim.timed(t["chunks"], session_id=case["case_id"], utterance_id=t["utterance_id"], offset_ms=off,
                         wrap_session=False, jitter=0.15, seed=7)
        n_words = sum(max(1, len(c.split())) for c in t["chunks"])
        off += n_words / 2.6 * 1000.0 + 500.0 + gap_ms
    evs.append(SessionEnd(session_id=case["case_id"]))
    return evs


def streaming(stacks, cases):
    rows, replay_ok = [], []
    for case in cases:
        st = stacks[case["corpus"]]
        run = run_virtual(st.cfg, st.service, st.policy, stream_inputs(case), index_hash=st.index_hash,
                          intent_stack=st.intent_stack)
        turns = {e.utterance_id: e.payload for e in run.events if e.type.value == "TURN_COMPLETED"}
        for t in case["turns"]:
            p = turns.get(t["utterance_id"], {})
            det = [c["type"] for c in p.get("session", {}).get("changes", [])]
            net = p.get("session", {}).get("net_change_types", [])
            rows.append({"case_id": case["case_id"], "utterance_id": t["utterance_id"], "detected": det,
                         "net": net, "change_ok_net": change_ok(net, t["gold"]),
                         "answer_changed": p.get("session", {}).get("answer_changed"),
                         "deferred": p.get("session", {}).get("deferred")})
        q = [e for e in run.events if e.type.value == "QUERY_GENERATED"]
        rep = ReplayEngine(st.cfg, st.service, st.policy, st.index_hash, st.intent_stack).replay(run.events)
        replay_ok.append({"case_id": case["case_id"], "identical": rep.identical, "events": rep.n_original,
                          "queries_generated": len(q),
                          "provisional_queries": sum(1 for e in q if e.payload["trigger"] == "provisional")})
    acc = sum(r["change_ok_net"] for r in rows) / len(rows)
    return {"turns": len(rows), "net_change_type_accuracy": round(acc, 4),
            "provisional_changes_per_turn": pct([len(r["detected"]) for r in rows]),
            "replay_exact": sum(r["identical"] for r in replay_ok), "sessions": len(replay_ok),
            "queries_generated": sum(r["queries_generated"] for r in replay_ok),
            "provisional_queries": sum(r["provisional_queries"] for r in replay_ok),
            "rows": rows, "replay": replay_ok}


def realtime_replay(stacks, cases, speed=4.0):
    case = next(c for c in cases if c["case_id"] == "S07")
    st = stacks["fixture"]
    cfg = st.cfg.model_copy(update={"streaming": st.cfg.streaming.model_copy(update={"speed": speed})})
    st2 = st.with_config(cfg)
    st2._intent_stack = st.intent_stack
    r = run_realtime(cfg, st2.service, st2.policy, stream_inputs(case), index_hash=st2.index_hash,
                     intent_stack=st2.intent_stack)
    rep = ReplayEngine(cfg, st2.service, st2.policy, st2.index_hash, st2.intent_stack).replay(r.events)
    return {"case_id": "S07", "speed": speed, "behavior_identical": rep.behavior_identical,
            "exact_identical": rep.identical, "n_events": rep.n_original,
            "behavior_differences": rep.behavior_differences[:5]}


